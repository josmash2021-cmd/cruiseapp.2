"""One-shot: bake simplified STATE outlines (Florida + Alabama) for the
driver zone map's state grouping (2026-10-14, user spec: the app opens
framing the zones of the STATE the driver is in — Florida and Alabama for
now — never the whole two-state union).

Downloads the US Census TIGERweb "States" GeoJSON (public domain US Gov
data), keeps FL (12) and AL (01), simplifies every outer ring
(Douglas-Peucker, ~1 km — the outlines only answer "which state is this
point/sector center in", never a boundary drawing), and writes
lib/services/state_outlines.dart.

Run from backend/:  ./.venv/Scripts/python.exe scripts/build_state_outlines.py
Idempotent: re-running just rewrites the Dart file.
"""

import json
import math
import os
import urllib.parse
import urllib.request

LAYER_URL = (
    "https://tigerweb.geo.census.gov/arcgis/rest/services/TIGERweb/"
    "State_County/MapServer/0/query"
)

STATES = {"12": "Fl", "01": "Al"}  # STFIPS -> Dart identifier suffix

TOLERANCE_DEG = 0.004  # ~450 m — grouping accuracy, not cartography
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                   "..", "..", "lib", "services", "state_outlines.dart")


def _perp_dist(p, a, b):
    """Perpendicular distance (deg) of p to segment a-b, equirectangular."""
    lat0 = math.radians((a[1] + b[1]) / 2)
    kx = math.cos(lat0)
    ax, ay = a[0] * kx, a[1]
    bx, by = b[0] * kx, b[1]
    px, py = p[0] * kx, p[1]
    dx, dy = bx - ax, by - ay
    if dx == 0 and dy == 0:
        return math.hypot(px - ax, py - ay)
    t = ((px - ax) * dx + (py - ay) * dy) / (dx * dx + dy * dy)
    t = max(0.0, min(1.0, t))
    return math.hypot(px - (ax + t * dx), py - (ay + t * dy))


def _dp(points, tol):
    """Douglas-Peucker (iterative) on a ring WITHOUT duplicating closure."""
    if len(points) <= 3:
        return points
    keep = [False] * len(points)
    keep[0] = keep[-1] = True
    stack = [(0, len(points) - 1)]
    while stack:
        i0, i1 = stack.pop()
        if i1 - i0 < 2:
            continue
        dmax, imax = 0.0, -1
        for i in range(i0 + 1, i1):
            d = _perp_dist(points[i], points[i0], points[i1])
            if d > dmax:
                dmax, imax = d, i
        if dmax > tol and imax > 0:
            keep[imax] = True
            stack.append((i0, imax))
            stack.append((imax, i1))
    return [p for p, k in zip(points, keep) if k]


def _simplify_ring(ring, tol):
    if len(ring) < 4:
        return ring
    closed = ring[0] == ring[-1]
    body = ring[:-1] if closed else ring
    out = _dp(body, tol)
    if closed and out:
        out = out + [out[0]]
    return out


def _outer_rings(geometry):
    """Outer ring of each polygon (state outlines have no holes that matter
    for point-in-state grouping)."""
    t = geometry.get("type")
    coords = geometry.get("coordinates") or []
    if t == "Polygon":
        for poly in coords[:1]:
            yield poly
    elif t == "MultiPolygon":
        for poly in coords:
            if poly:
                yield poly[0]


def _fetch_states():
    params = urllib.parse.urlencode({
        "where": "STATE IN ('" + "','".join(STATES) + "')",
        "outFields": "STATE,NAME",
        "outSR": "4326",
        "f": "geojson",
        "returnGeometry": "true",
    })
    req = urllib.request.Request(
        f"{LAYER_URL}?{params}", headers={"User-Agent": "cruise-zone-bakeoff/1.0"})
    with urllib.request.urlopen(req, timeout=120) as r:
        return json.loads(r.read().decode("utf-8"))


def main():
    data = _fetch_states()
    by_state = {}
    for feat in data.get("features", []):
        props = feat.get("properties") or {}
        stfips = str(props.get("STATE") or "").zfill(2)
        if stfips in STATES:
            by_state[stfips] = feat

    missing = sorted(set(STATES) - set(by_state))
    if missing:
        raise SystemExit(f"states not found in TIGER response: {missing}")

    lines = [
        "/// GENERATED by backend/scripts/build_state_outlines.py — Census",
        "/// TIGERweb state boundaries simplified to ~450 m. Do not hand-edit;",
        "/// re-run the script. Point-in-state = any ring contains (the",
        "/// tolerance is for grouping the zone fit, not drawing).",
        "library;",
        "",
    ]
    total_pts = 0
    for stfips, feat in sorted(by_state.items(), key=lambda kv: STATES[kv[0]]):
        suffix = STATES[stfips]
        rings = []
        for ring in _outer_rings(feat["geometry"]):
            ring = _simplify_ring(ring, TOLERANCE_DEG)
            if len(ring) >= 4:
                rings.append(ring)
        if not rings:
            raise SystemExit(f"state {stfips}: empty after simplifying")
        total_pts += sum(len(r) for r in rings)
        lines.append(f"const List<List<double>> kStateOutline{suffix} = [")
        for ring in rings:
            # Flat [lng, lat, lng, lat, ...] — ZoneService._flatRingContains
            # walks it in strides of 2.
            pts = ", ".join(f"{p[0]:.5f},{p[1]:.5f}" for p in ring)
            lines.append(f"  [{pts}],")
        lines.append("];")
        lines.append("")

    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    size = os.path.getsize(OUT)
    print(f"OK: {len(by_state)} states, {total_pts} points, "
          f"{size/1024:.1f} KB -> {OUT}")


if __name__ == "__main__":
    main()
